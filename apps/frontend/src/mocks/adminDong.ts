// /ops 운영자 등록 화면 전용 행정동(관악구) 선택 데이터.
//
// 복지관 직원도 행정동 코드(예: 1162064500)를 외우지 못한다는 전제에서
// 출발한다. 폼에서 코드를 직접 입력받지 않고 동 이름으로 고르면 코드가
// 자동으로 채워지도록, 이름-코드 쌍을 제공한다.
//
// 중요: 발송 매칭 키는 행정동 코드다. 잘못된 코드를 올리면 등록자가 엉뚱한
// 행정동 경보를 받거나 자기 동 경보에서 누락된다. 그래서 공식 자료로 검증된
// 하나의 동만 선택지로 둔다.
//
// 현재 데모 범위는 관악구 서원동 하나뿐이다. 다른 동 코드는 공식 자료로
// 확인을 마치기 전까지 이 목록에 추가하지 않는다.

export interface AdminDong {
  // 행정동 코드(숫자 10자리 문자열). 발송 매칭 키.
  code: string
  // 행정동 이름.
  name: string
}

// 현재 데모 범위에서 검증된 단일 행정동. 새 동을 추가하려면 공식 자료로
// 코드를 검증한 뒤에만 이 목록에 올린다.
export const ADMIN_DONG: ReadonlyArray<AdminDong> = [
  { code: '1162064500', name: '서원동' },
]
